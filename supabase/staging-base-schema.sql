create extension if not exists pgcrypto;

create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.site_settings (
  key text primary key,
  value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

-- Current production uses BIGINT product IDs and numeric prices.
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  category text not null check (category in (
    'followers','account','video_views','video_likes','video_comments','product_likes'
  )),
  qty integer not null,
  price numeric not null,
  original numeric,
  sold text,
  image_url text,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz default now(),
  constraint products_category_qty_key unique (category, qty)
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  transaction_id text not null unique,
  category text not null check (category in (
    'followers','account','video_views','video_likes','video_comments','product_likes'
  )),
  product_name text not null,
  quantity integer not null default 0,
  amount bigint not null default 0,
  customer_whatsapp text,
  shopee_link text,
  account_name text,
  account_contact text,
  payment_status text not null default 'pending',
  order_status text not null default 'pending',
  created_at timestamptz not null default now(),
  paid_at timestamptz,
  updated_at timestamptz not null default now(),
  -- Production product IDs are BIGINT while orders.product_id is UUID.
  -- Keep this nullable UUID field for compatibility with current application code.
  product_id uuid,
  payment_method text,
  photo_url text,
  photo_path text,
  comment_text text
);

create index if not exists orders_created_at_idx on public.orders(created_at desc);
create index if not exists orders_payment_status_idx on public.orders(payment_status);
create index if not exists orders_transaction_id_idx on public.orders(transaction_id);

create table if not exists public.payments (
  id uuid primary key default gen_random_uuid(),
  partner_reference_no text not null unique,
  dana_reference_no text,
  category text not null check (category in (
    'followers','account','video_views','video_likes','video_comments','product_likes'
  )),
  product_qty integer not null,
  amount numeric not null,
  customer_whatsapp text,
  shopee_link text,
  account_contact text,
  status text not null default 'PENDING'
    check (status in ('PENDING','PAID','EXPIRED','FAILED')),
  qr_content text,
  qr_image text,
  qr_url text,
  expires_at timestamptz,
  paid_at timestamptz,
  dana_payload jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists payments_created_at_idx on public.payments(created_at);
create index if not exists payments_dana_reference_idx on public.payments(dana_reference_no);
create index if not exists payments_status_idx on public.payments(status);

create table if not exists public.analytics_events (
  id bigint generated by default as identity primary key,
  visitor_id text not null,
  session_id text,
  event_type text not null,
  page_path text,
  product_id text,
  product_name text,
  quantity integer,
  value bigint default 0,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admins where user_id = auth.uid()
  );
$$;

revoke all on function public.is_admin() from public, anon;
grant execute on function public.is_admin() to authenticated;

alter table public.admins enable row level security;
alter table public.site_settings enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.payments enable row level security;
alter table public.analytics_events enable row level security;

grant select on public.site_settings, public.products to anon, authenticated;
grant insert, update, delete on public.site_settings, public.products to authenticated;
grant select on public.orders, public.payments, public.analytics_events to authenticated;
grant insert on public.analytics_events to anon, authenticated;

drop policy if exists "public read site settings" on public.site_settings;
create policy "public read site settings" on public.site_settings
  for select to anon, authenticated using (true);
drop policy if exists "admin manage site settings" on public.site_settings;
create policy "admin manage site settings" on public.site_settings
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "public read products" on public.products;
create policy "public read products" on public.products
  for select to anon, authenticated using (true);
drop policy if exists "admin manage products" on public.products;
create policy "admin manage products" on public.products
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "admin read orders" on public.orders;
create policy "admin read orders" on public.orders
  for select to authenticated using (public.is_admin());
drop policy if exists "admin read payments" on public.payments;
create policy "admin read payments" on public.payments
  for select to authenticated using (public.is_admin());
drop policy if exists "admin update payments" on public.payments;
create policy "admin update payments" on public.payments
  for update to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "admin read analytics events" on public.analytics_events;
create policy "admin read analytics events" on public.analytics_events
  for select to authenticated using (public.is_admin());
drop policy if exists "public insert analytics events" on public.analytics_events;
create policy "public insert analytics events" on public.analytics_events
  for insert to anon, authenticated
  with check (
    event_type = any (array['page_view','product_click','checkout_started','checkout_paid','ad_click'])
    and length(visitor_id) between 8 and 128
  );

-- Identity sequences used by products and public analytics inserts.
grant usage, select on sequence public.products_id_seq to authenticated;
grant usage, select on sequence public.analytics_events_id_seq to anon, authenticated;

-- Order photos used by checkout: only image uploads under orders/ are allowed.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'order-photos', 'order-photos', true, 3145728,
  array['image/jpeg','image/png','image/webp']::text[]
)
on conflict (id) do update set
  public = true,
  file_size_limit = 3145728,
  allowed_mime_types = array['image/jpeg','image/png','image/webp']::text[];

drop policy if exists "public read order photos" on storage.objects;
create policy "public read order photos" on storage.objects
  for select using (bucket_id = 'order-photos');
drop policy if exists "public upload order photos" on storage.objects;
create policy "public upload order photos" on storage.objects
  for insert to anon, authenticated
  with check (
    bucket_id = 'order-photos'
    and name like 'orders/%'
    and lower(storage.extension(name)) in ('jpg','jpeg','png','webp')
    and coalesce(metadata->>'mimetype','') in ('image/jpeg','image/png','image/webp')
  );

